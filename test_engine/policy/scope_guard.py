from urllib.parse import urlparse
from typing import Set
import logging

logger = logging.getLogger("test_engine.policy.scope_guard")

class ScopeGuard:
    """Playwright route interceptor that blocks network egress outside allowed domains."""

    def __init__(self, allowed_hostnames: Set[str], allow_common_cdns: bool = True):
        self.allowed_hostnames = {h.lower() for h in allowed_hostnames}
        self.allow_common_cdns = allow_common_cdns
        self.common_cdns = {
            "cdnjs.cloudflare.com",
            "cdn.jsdelivr.net",
            "fonts.googleapis.com",
            "fonts.gstatic.com",
            "unpkg.com",
            "ajax.googleapis.com"
        }

    async def intercept_route(self, route, request):
        """Intercept every network request generated by Playwright browser."""
        url = request.url
        try:
            parsed = urlparse(url)
            hostname = parsed.hostname.lower() if parsed.hostname else ""

            # Check if domain is allowed
            is_allowed = (
                hostname in self.allowed_hostnames or
                any(hostname.endswith("." + h) for h in self.allowed_hostnames) or
                (self.allow_common_cdns and hostname in self.common_cdns)
            )

            if is_allowed:
                await route.continue_()
            else:
                logger.warning(f"Scope Guard blocked out-of-scope egress request: {url}")
                await route.abort()
        except Exception as e:
            logger.error(f"Error in ScopeGuard route interception: {e}")
            await route.abort()
