import asyncio
import ipaddress
import time
import socket
from urllib.parse import urlparse
from typing import Any, Dict, Set
import logging

logger = logging.getLogger("test_engine.policy.scope_guard")

class ScopeGuard:
    """Playwright route interceptor that blocks network egress outside allowed domains."""

    def __init__(
        self,
        allowed_hostnames: Set[str],
        allow_common_cdns: bool = True,
        max_requests_per_second: int = 10,
        target_url: str = "",
    ):
        self.allowed_hostnames = {h.lower().strip().rstrip(".") for h in allowed_hostnames}
        self.allow_common_cdns = allow_common_cdns
        self.request_interval = 1.0 / max(1, max_requests_per_second)
        try:
            target = urlparse(target_url)
            self.target_scheme = target.scheme.lower()
            self.target_port = target.port
        except ValueError:
            self.target_scheme = ""
            self.target_port = None
        self._rate_lock = asyncio.Lock()
        self._dns_lock = asyncio.Lock()
        self._next_request_at = 0.0
        self._public_host_cache: Dict[str, bool] = {}
        self.common_cdns = {
            "cdnjs.cloudflare.com",
            "cdn.jsdelivr.net",
            "fonts.googleapis.com",
            "fonts.gstatic.com",
            "unpkg.com",
            "ajax.googleapis.com"
        }

    def _is_allowed_host(self, hostname: str) -> bool:
        hostname = hostname.lower().rstrip(".")
        for pattern in self.allowed_hostnames:
            if pattern.startswith("*."):
                suffix = pattern[2:]
                if hostname != suffix and hostname.endswith("." + suffix):
                    return True
            elif hostname == pattern:
                return True
        return self.allow_common_cdns and hostname in self.common_cdns

    async def _throttle_request(self) -> None:
        async with self._rate_lock:
            now = time.monotonic()
            wait = max(0.0, self._next_request_at - now)
            self._next_request_at = max(now, self._next_request_at) + self.request_interval
            if wait:
                await asyncio.sleep(wait)

    async def _host_resolves_publicly(self, hostname: str) -> bool:
        try:
            return ipaddress.ip_address(hostname).is_global
        except ValueError:
            pass
        async with self._dns_lock:
            if hostname in self._public_host_cache:
                return self._public_host_cache[hostname]
            try:
                loop = asyncio.get_running_loop()
                records = await asyncio.wait_for(
                    loop.getaddrinfo(hostname, None, type=socket.SOCK_STREAM), timeout=2.0
                )
                is_public = bool(records) and all(
                    ipaddress.ip_address(record[4][0]).is_global for record in records
                )
            except Exception:
                is_public = False
            self._public_host_cache[hostname] = is_public
            return is_public

    async def intercept_route(self, route: Any, request: Any) -> None:
        """Intercept every network request generated by Playwright browser."""
        url = request.url
        try:
            parsed = urlparse(url)
            hostname = parsed.hostname.lower() if parsed.hostname else ""
            port = parsed.port
            standard_port = 443 if parsed.scheme.lower() == "https" else 80
            allowed_port = port in (None, standard_port) or (
                parsed.scheme.lower() == self.target_scheme and port == self.target_port
            )

            if (
                parsed.scheme.lower() in {"http", "https"}
                and not parsed.username
                and not parsed.password
                and allowed_port
                and self._is_allowed_host(hostname)
                and await self._host_resolves_publicly(hostname)
            ):
                await self._throttle_request()
                await route.continue_()
            else:
                logger.warning("Scope Guard blocked egress request to host: %s", hostname or "[unknown]")
                await route.abort()
        except Exception as e:
            logger.error("ScopeGuard failed closed (%s)", type(e).__name__)
            await route.abort()
